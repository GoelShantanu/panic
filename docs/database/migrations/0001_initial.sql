CREATE FUNCTION ensure_monthly_partitions(p_parent regclass, p_months_ahead integer) RETURNS void
LANGUAGE plpgsql AS $$
DECLARE
  v_month date := date_trunc('month', now() AT TIME ZONE 'UTC')::date;
  v_from  date;
  v_to    date;
  i       integer;
BEGIN
  FOR i IN 0..p_months_ahead LOOP
    v_from := (v_month + make_interval(months => i))::date;
    v_to   := (v_month + make_interval(months => i + 1))::date;
    EXECUTE format('CREATE TABLE IF NOT EXISTS %I PARTITION OF %s FOR VALUES FROM (%L) TO (%L)',
                   p_parent::text || '_' || to_char(v_from, 'YYYYMM'), p_parent,
                   v_from::timestamp AT TIME ZONE 'UTC', v_to::timestamp AT TIME ZONE 'UTC');
  END LOOP;
END $$;

CREATE FUNCTION ensure_daily_partitions(p_parent regclass, p_days_ahead integer) RETURNS void
LANGUAGE plpgsql AS $$
DECLARE
  v_day date := (now() AT TIME ZONE 'UTC')::date;
  v_from date;
  i integer;
BEGIN
  FOR i IN 0..p_days_ahead LOOP
    v_from := v_day + i;
    EXECUTE format('CREATE TABLE IF NOT EXISTS %I PARTITION OF %s FOR VALUES FROM (%L) TO (%L)',
                   p_parent::text || '_' || to_char(v_from, 'YYYYMMDD'), p_parent,
                   v_from::timestamp AT TIME ZONE 'UTC', (v_from + 1)::timestamp AT TIME ZONE 'UTC');
  END LOOP;
END $$;

