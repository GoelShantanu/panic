-- PRD-002 C-002.8: an excerpt only where the source's access basis allows it.
CREATE FUNCTION item_excerpt_allowed() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.excerpt IS NOT NULL AND NOT (SELECT excerpt_allowed FROM source WHERE source_id = NEW.source_id) THEN
    RAISE EXCEPTION 'PRD-002 C-002.8: source % does not permit excerpts', NEW.source_id;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER item_excerpt_allowed BEFORE INSERT OR UPDATE OF excerpt, source_id ON item
  FOR EACH ROW EXECUTE FUNCTION item_excerpt_allowed();

