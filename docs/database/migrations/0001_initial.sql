-- PRD-004 US-004.1 AC-1: a live story always has at least one event type.
CREATE FUNCTION assert_story_has_event_type(p_story bigint) RETURNS void
LANGUAGE plpgsql AS $$
BEGIN
  IF EXISTS (SELECT 1 FROM story WHERE id = p_story AND merged_into IS NULL)
     AND NOT EXISTS (SELECT 1 FROM story_event_type WHERE story_id = p_story) THEN
    RAISE EXCEPTION 'PRD-004 US-004.1 AC-1: story % has no event type', p_story;
  END IF;
END $$;

CREATE FUNCTION story_inserted_check_event_type() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  PERFORM assert_story_has_event_type(NEW.id);
  RETURN NULL;
END $$;

CREATE FUNCTION event_type_removed_check_story() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  PERFORM assert_story_has_event_type(OLD.story_id);
  RETURN NULL;
END $$;

CREATE CONSTRAINT TRIGGER story_requires_event_type
  AFTER INSERT ON story DEFERRABLE INITIALLY DEFERRED
  FOR EACH ROW EXECUTE FUNCTION story_inserted_check_event_type();
CREATE CONSTRAINT TRIGGER story_keeps_event_type
  AFTER DELETE OR UPDATE OF story_id ON story_event_type DEFERRABLE INITIALLY DEFERRED
  FOR EACH ROW EXECUTE FUNCTION event_type_removed_check_story();

