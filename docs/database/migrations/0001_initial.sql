CREATE TABLE story_vote_count (
  story_id  bigint PRIMARY KEY REFERENCES story (id),
  bullish   integer NOT NULL DEFAULT 0 CHECK (bullish >= 0),
  bearish   integer NOT NULL DEFAULT 0 CHECK (bearish >= 0),
  neutral   integer NOT NULL DEFAULT 0 CHECK (neutral >= 0),
  important integer NOT NULL DEFAULT 0 CHECK (important >= 0)
);

CREATE FUNCTION refresh_story_vote_count(p_story bigint) RETURNS void
LANGUAGE sql AS $$
  INSERT INTO story_vote_count (story_id, bullish, bearish, neutral, important)
  SELECT p_story,
    (SELECT count(*) FROM vote_directional WHERE story_id = p_story AND direction = 'bullish' AND discounted_at IS NULL),
    (SELECT count(*) FROM vote_directional WHERE story_id = p_story AND direction = 'bearish' AND discounted_at IS NULL),
    (SELECT count(*) FROM vote_directional WHERE story_id = p_story AND direction = 'neutral' AND discounted_at IS NULL),
    (SELECT count(*) FROM vote_quality     WHERE story_id = p_story AND kind = 'important'   AND discounted_at IS NULL)
  ON CONFLICT (story_id) DO UPDATE
    SET bullish = EXCLUDED.bullish, bearish = EXCLUDED.bearish,
        neutral = EXCLUDED.neutral, important = EXCLUDED.important
$$;

CREATE FUNCTION vote_changed() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    PERFORM refresh_story_vote_count(NEW.story_id);
  ELSIF TG_OP = 'DELETE' THEN
    PERFORM refresh_story_vote_count(OLD.story_id);
  ELSE
    PERFORM refresh_story_vote_count(NEW.story_id);
    IF OLD.story_id <> NEW.story_id THEN
      PERFORM refresh_story_vote_count(OLD.story_id);
    END IF;
  END IF;
  RETURN NULL;
END $$;
CREATE TRIGGER vote_directional_count AFTER INSERT OR UPDATE OR DELETE ON vote_directional
  FOR EACH ROW EXECUTE FUNCTION vote_changed();
CREATE TRIGGER vote_quality_count AFTER INSERT OR UPDATE OR DELETE ON vote_quality
  FOR EACH ROW EXECUTE FUNCTION vote_changed();

