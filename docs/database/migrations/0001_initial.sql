-- =====================================================================
-- §1  GUARDRAILS §4.3 / D-014 — no AI tone or sentiment storage, ever.
-- Any table, view or column whose name contains the word "tone" or
-- "sentiment" (as a whole underscore-delimited word) is rejected at DDL time.
-- =====================================================================

CREATE FUNCTION forbid_tone_columns() RETURNS event_trigger
LANGUAGE plpgsql AS $$
DECLARE r record;
BEGIN
  FOR r IN
    SELECT c.relname, a.attname
    FROM pg_event_trigger_ddl_commands() cmd
    JOIN pg_class c ON c.oid = cmd.objid
    LEFT JOIN pg_attribute a
      ON a.attrelid = c.oid AND a.attnum > 0 AND NOT a.attisdropped
    WHERE cmd.classid = 'pg_class'::regclass
      AND (c.relname ~* '(^|_)(tone|sentiment)(_|$)'
           OR a.attname ~* '(^|_)(tone|sentiment)(_|$)')
  LOOP
    RAISE EXCEPTION 'GUARDRAILS 4.3 / D-014: %.% would store AI tone or sentiment',
      r.relname, coalesce(r.attname, '*');
  END LOOP;
END $$;

CREATE EVENT TRIGGER no_tone_columns ON ddl_command_end
  WHEN TAG IN ('CREATE TABLE', 'ALTER TABLE', 'CREATE TABLE AS',
               'CREATE VIEW', 'CREATE MATERIALIZED VIEW')
  EXECUTE FUNCTION forbid_tone_columns();

