-- PRD-001 US-001.1 AC-4: rows never move; identities never change.
CREATE FUNCTION story_immutable_fields() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.first_seen_at IS DISTINCT FROM OLD.first_seen_at THEN
    RAISE EXCEPTION 'PRD-001 US-001.1 AC-4: story.first_seen_at is immutable';
  END IF;
  IF NEW.public_id IS DISTINCT FROM OLD.public_id THEN
    RAISE EXCEPTION 'story.public_id is immutable';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER story_immutable_fields BEFORE UPDATE ON story
  FOR EACH ROW EXECUTE FUNCTION story_immutable_fields();

-- Denormalised story time, copied from story (immutable), for index-ordered scans.
CREATE FUNCTION copy_story_first_seen() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  SELECT first_seen_at INTO NEW.story_first_seen_at FROM story WHERE id = NEW.story_id;
  RETURN NEW;
END $$;

