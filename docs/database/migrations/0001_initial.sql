-- PRD-007 US-007.2: reserved names, current NSE symbols, and held names are unavailable.
CREATE FUNCTION username_available() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.username IS NULL THEN RETURN NEW; END IF;
  IF EXISTS (SELECT 1 FROM reserved_username WHERE name = NEW.username) THEN
    RAISE EXCEPTION 'username_reserved: %', NEW.username;
  END IF;
  IF EXISTS (SELECT 1 FROM instrument_code
             WHERE exchange = 'NSE' AND upper(code) = upper(NEW.username::text)
               AND valid @> current_date) THEN
    RAISE EXCEPTION 'username_reserved: % is an NSE symbol', NEW.username;
  END IF;
  IF EXISTS (SELECT 1 FROM username_hold
             WHERE username = NEW.username AND held_until > now() AND user_id <> NEW.id) THEN
    RAISE EXCEPTION 'username_reserved: % is held', NEW.username;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER app_user_username_available BEFORE INSERT OR UPDATE OF username ON app_user
  FOR EACH ROW EXECUTE FUNCTION username_available();

