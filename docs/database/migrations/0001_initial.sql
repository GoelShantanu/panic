CREATE TABLE instrument (
  isin           isin_code PRIMARY KEY,
  segment        instrument_segment NOT NULL,
  status         instrument_status NOT NULL DEFAULT 'listed',
  listed_on      date,
  successor_isin isin_code REFERENCES instrument (isin),
  created_at     timestamptz NOT NULL DEFAULT now(),
  CHECK (successor_isin IS NULL OR successor_isin <> isin),
  CHECK (status <> 'merged' OR successor_isin IS NOT NULL)
);

CREATE TABLE instrument_code (
  id       bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  isin     isin_code NOT NULL REFERENCES instrument (isin),
  exchange exchange_code NOT NULL,
  code     text NOT NULL CHECK (code <> ''),
  valid    daterange NOT NULL CHECK (NOT isempty(valid) AND NOT lower_inf(valid)),
  -- one code means one instrument at any moment, per exchange
  EXCLUDE USING gist (exchange WITH =, code WITH =, valid WITH &&),
  -- one instrument has one code per exchange at any moment
  EXCLUDE USING gist (isin WITH =, exchange WITH =, valid WITH &&)
);
CREATE INDEX instrument_code_trgm ON instrument_code USING gin (code gin_trgm_ops);

CREATE TABLE instrument_name (
  id    bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  isin  isin_code NOT NULL REFERENCES instrument (isin),
  kind  text NOT NULL CHECK (kind IN ('legal', 'short')),
  name  text NOT NULL CHECK (name <> ''),
  valid daterange NOT NULL CHECK (NOT isempty(valid) AND NOT lower_inf(valid)),
  EXCLUDE USING gist (isin WITH =, kind WITH =, valid WITH &&)
);
CREATE INDEX instrument_name_trgm ON instrument_name USING gin (lower(name) gin_trgm_ops);

CREATE TABLE instrument_alias (
  id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  isin        isin_code NOT NULL REFERENCES instrument (isin),
  alias       text NOT NULL CHECK (alias <> ''),
