-- Depth from parent; a reply to a level-3 comment is placed at level 3 (PRD-006 US-006.2 AC-1).
CREATE FUNCTION comment_set_depth() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE p record;
BEGIN
  IF NEW.parent_id IS NULL THEN
    NEW.depth := 1;
  ELSE
    SELECT id, parent_id, depth INTO p FROM comment WHERE id = NEW.parent_id;
    IF NOT FOUND THEN RAISE EXCEPTION 'parent comment % not found', NEW.parent_id; END IF;
    IF p.depth >= 3 THEN
      NEW.parent_id := p.parent_id;
      NEW.depth := 3;
    ELSE
      NEW.depth := p.depth + 1;
    END IF;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER comment_set_depth BEFORE INSERT ON comment
  FOR EACH ROW EXECUTE FUNCTION comment_set_depth();

